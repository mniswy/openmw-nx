#!/usr/bin/env python3
"""Generates nxgl_stubs.inc from the Mesa headers shipped by devkitPro's switch-mesa package.

Mesa on Switch exports no desktop OpenGL entry points; they can only be obtained at runtime through
eglGetProcAddress. This script emits one forwarding stub per function declared in GL/gl.h and GL/glext.h
so that code written against a regular libGL (OpenSceneGraph, OpenMW) links unchanged.

Usage (from any shell that can run the cross compiler):
    python generate.py [path/to/aarch64-none-elf-gcc] [path/to/portlibs/switch/include]

The output is checked in. Regenerate it only when switch-mesa is updated.
"""

import os
import re
import subprocess
import sys

DEVKITPRO = os.environ.get("DEVKITPRO_WIN", "C:/devkitPro")
GCC = sys.argv[1] if len(sys.argv) > 1 else DEVKITPRO + "/devkitA64/bin/aarch64-none-elf-gcc"
INCLUDE = sys.argv[2] if len(sys.argv) > 2 else DEVKITPRO + "/portlibs/switch/include"
OUTPUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "nxgl_stubs.inc")

SOURCE = "#define GL_GLEXT_PROTOTYPES 1\n#include <GL/gl.h>\n#include <GL/glext.h>\n"

DECLARATION = re.compile(
    r'(?:extern|__attribute__\s*\(\(\s*visibility\s*\(\s*"default"\s*\)\s*\)\))\s+'
    r"(?P<ret>[A-Za-z_][\w\s\*]*?)\s*\b(?P<name>gl[A-Z]\w*)\s*\((?P<params>[^()]*)\)\s*;"
)
PARAMETER = re.compile(r"^(?P<type>.*?[\s\*])(?P<name>[A-Za-z_]\w*)\s*(?P<array>(\[[^\]]*\])*)$", re.S)


def preprocess():
    result = subprocess.run(
        [GCC, "-E", "-P", "-x", "c", "-I", INCLUDE, "-"], input=SOURCE, capture_output=True, text=True, check=True
    )
    return result.stdout


def parse_parameters(name, text):
    text = " ".join(text.split())
    if text in ("", "void"):
        return "void", ""
    declared = []
    forwarded = []
    for index, parameter in enumerate(text.split(",")):
        parameter = parameter.strip()
        match = PARAMETER.match(parameter)
        if match is None or match.group("name") in TYPE_WORDS:
            # Unnamed parameter: give it a name so that it can be forwarded.
            declared.append(f"{parameter} nxgl_arg{index}")
            forwarded.append(f"nxgl_arg{index}")
            continue
        declared.append(parameter)
        forwarded.append(match.group("name"))
    return ", ".join(declared), ", ".join(forwarded)


TYPE_WORDS = {"void", "int", "char", "short", "long", "float", "double", "unsigned", "signed", "const"}


def main():
    seen = {}
    for match in DECLARATION.finditer(preprocess()):
        name = match.group("name")
        if name in seen:
            continue
        ret = " ".join(match.group("ret").split())
        params, args = parse_parameters(name, match.group("params"))
        seen[name] = (ret, params, args)

    if len(seen) < 2000:
        raise SystemExit(f"only {len(seen)} declarations found, the header format probably changed")

    lines = [
        "// Generated by generate.py from the switch-mesa GL/gl.h and GL/glext.h. Do not edit.",
        f"// {len(seen)} entry points.",
        "",
    ]
    for name in sorted(seen):
        ret, params, args = seen[name]
        if ret == "void":
            lines.append(f"NXGL_VOID({name}, ({params}), ({args}))")
        else:
            lines.append(f"NXGL_RET({ret}, {name}, ({params}), ({args}))")
    with open(OUTPUT, "w", newline="\n") as stream:
        stream.write("\n".join(lines) + "\n")
    print(f"wrote {len(seen)} stubs to {OUTPUT}")


if __name__ == "__main__":
    main()
